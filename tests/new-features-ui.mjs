import { chromium, expect } from "@playwright/test";
import assert from "node:assert/strict";
import { readFile, mkdir } from "node:fs/promises";

const browser = await chromium.launch(process.platform === "win32" ? { channel: "msedge", headless: true } : { headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, locale: "zh-CN" });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const user = { id: "u1", nickname: "测试作者", email: "fixture@example.test", role: "member", permissions: [] };
await page.route("**/api/bootstrap", (r) => r.fulfill({ json: { user, config: { registrationEnabled: true, maxUploadBytes: 52428800 } } }));
await page.route("**/api/me/notifications", (r) => r.fulfill({ json: { items: [], unreadCount: 2 } }));
await page.route("**/api/articles?*", (r) => r.fulfill({ json: { items: [], total: 0 } }));
await page.route("**/api/articles/a1", (r) => r.fulfill({ json: { id: "a1", title: "真实文章", body: "正文", author: { id: "u2", nickname: "公开作者" }, attachments: [] } }));
let commentSort = "";
await page.route("**/api/comments?*", (r) => {
  commentSort = new URL(r.request().url()).searchParams.get("sort");
  return r.fulfill({ json: { items: [{ id: "c1", body: "主评论内容", author: { id: "u2", nickname: "公开作者" }, likeCount: 3, liked: false, canDelete: false, canReply: true }], total: 1, page: 1, pageSize: 20 } });
});
let replyPayload, reportPayload, liked = false;
await page.route("**/api/comments", (r) => { replyPayload = r.request().postDataJSON(); return r.fulfill({ json: { ok: true } }); });
await page.route("**/api/comments/c1/report", (r) => { reportPayload = r.request().postDataJSON(); return r.fulfill({ json: { ok: true } }); });
await page.route("**/api/comments/c1/like", (r) => { liked = true; return r.fulfill({ json: { liked: true, likeCount: 4 } }); });
await page.route("**/api/problems?*", async (r) => { await new Promise((x) => setTimeout(x, 350)); return r.fulfill({ json: { items: [{ id: "p1", title: "不应串入文章页的赛题", problemCode: "A" }], total: 1, facets: {} } }); });
await page.route("**/api/problems/p1", (r) => r.fulfill({ json: { id: "p1", title: "PDF 赛题", category: "signal", attachments: [{ id: "f1", name: "题目.pdf", mimeType: "application/pdf", url: "/api/official-files/f1" }] } }));
const pdf = await readFile("server/seed/problems-official-files/2026/all/H.pdf");
await page.route("**/api/official-files/f1", (r) => r.fulfill({ status: 200, headers: { "Content-Type": "application/pdf", "Content-Length": String(pdf.length) }, body: pdf }));
await page.route("**/api/users/u2", (r) => r.fulfill({ json: { id: "u2", nickname: "公开作者", bio: "公开简介", articles: [{ id: "a1", title: "真实文章" }], comments: [{ id: "c1", body: "公开互动", targetTitle: "真实文章", href: "/articles/a1#comment-c1" }], reviews: [] } }));
await page.route("**/api/shops/s1", (r) => r.fulfill({ json: { id: "s1", name: "真实店铺", reviews: [], bookmarked: false } }));
let bookmarked = false;
await page.route("**/api/me/bookmarks/shop/s1", (r) => { bookmarked = r.request().method() === "POST"; return r.fulfill({ json: { ok: true } }); });
await page.route("**/api/articles/drafts", (r) => r.fulfill({ json: { id: "d1" } }));
let createdDraftReloads = 0;
await page.route("**/api/articles/drafts/*", async (r) => {
  const key = new URL(r.request().url()).pathname.split("/").pop();
  if (key === "d1") createdDraftReloads += 1;
  if (key === "missing") return r.fulfill({ status: 404, json: { error: "草稿不存在", code: "NOT_FOUND" } });
  if (key === "draft-a") await new Promise((x) => setTimeout(x, 350));
  return r.fulfill({ json: { id: key, title: key === "draft-a" ? "A稿标题" : "B稿标题", category: "基础知识", tags: [], excerpt: "", body: key === "draft-a" ? "A稿正文" : "B稿正文" } });
});
let imageField = "";
await page.route("**/api/articles/drafts/d1/images", async (r) => { imageField = (await r.request().postDataBuffer())?.toString("latin1") || ""; return r.fulfill({ json: { id: "img1", name: "diagram.png", markdownUrl: "/api/article-images/img1", markdown: "![diagram.png](/api/article-images/img1)" } }); });
const base = process.env.PREVIEW_BASE || "http://127.0.0.1:5173";

await page.goto(`${base}/problems`);
await page.goto(`${base}/articles`);
await expect(page.getByRole("heading", { name: "学习文章" })).toBeVisible();
await page.waitForTimeout(500);
await expect(page.getByText("不应串入文章页的赛题")).toHaveCount(0);
await page.goBack(); await page.goForward();
await expect(page.getByText("不应串入文章页的赛题")).toHaveCount(0);

await page.goto(`${base}/articles/a1`);
await page.getByRole("button", { name: "回复" }).click();
await page.getByLabel("回复 公开作者").fill("内嵌回复内容");
await page.getByRole("button", { name: "提交" }).click();
await expect.poll(() => replyPayload?.parentId).toBe("c1");
await page.getByRole("button", { name: "举报" }).click();
await page.getByLabel("举报原因").fill("需要管理员核查");
await page.getByRole("button", { name: "提交" }).click();
assert.equal(reportPayload.reason, "需要管理员核查");
await page.getByRole("button", { name: "赞 3" }).click(); assert.equal(liked, true);
await page.getByRole("button", { name: "最新" }).click(); await expect.poll(() => commentSort).toBe("latest");
await page.getByRole("link", { name: "公开作者" }).first().click();
await expect(page.getByRole("heading", { name: "公开作者", exact: true })).toBeVisible();
await expect(page.getByText("公开互动")).toBeVisible();

await page.goto(`${base}/shops/s1`);
await page.getByRole("button", { name: "收藏" }).click();
await expect(page.getByRole("button", { name: "取消收藏" })).toBeVisible(); assert.equal(bookmarked, true);

await page.goto(`${base}/write`);
await expect(page.getByRole("heading", { name: "写文章" })).toBeVisible();
await page.locator(".markdown-toolbar button").click();
await expect(page.locator("textarea.editor-textarea")).toHaveValue(/\[链接文字\]\(https:\/\/example\.com\)/);
await page.locator('.toolbar-upload input[type="file"]').setInputFiles({ name: "diagram.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9ZQmcAAAAASUVORK5CYII=", "base64") });
await expect(page.getByText("图片已上传并插入正文，请继续保存草稿")).toBeVisible();
await expect(page.locator("textarea.editor-textarea")).toHaveValue(/\/api\/article-images\/img1/);
assert.match(imageField, /name="image"/);
assert.equal(createdDraftReloads, 0, "newly created draft must not reload and overwrite current edits");
await page.goto(`${base}/write?draft=draft-a`);
await page.goto(`${base}/write?draft=draft-b`);
await expect(page.getByLabel("标题")).toHaveValue("B稿标题");
await page.waitForTimeout(450);
await expect(page.getByLabel("标题")).toHaveValue("B稿标题");
await page.goBack();
await expect(page.getByLabel("标题")).toHaveValue("A稿标题");
await page.goto(`${base}/write?draft=missing`);
await expect(page.getByRole("heading", { name: "无法打开草稿" })).toBeVisible();
await expect(page.getByText("草稿不存在")).toBeVisible();
await expect(page.locator("textarea.editor-textarea")).toHaveCount(0);
await expect(page.getByText("A稿正文")).toHaveCount(0);
await expect(page.getByRole("button", { name: "重试" })).toBeVisible();

await page.goto(`${base}/problems/p1`);
await expect(page.getByLabel(/PDF 阅读器/)).toBeVisible();
assert.equal(await page.evaluate(() => {
  const reader = document.querySelector(".pdf-reader-section"), body = document.querySelector(".official-body-note"), downloads = document.querySelector(".attachments");
  return !!reader && !!body && !!downloads && !!(reader.compareDocumentPosition(body) & Node.DOCUMENT_POSITION_FOLLOWING) && !!(reader.compareDocumentPosition(downloads) & Node.DOCUMENT_POSITION_FOLLOWING);
}), true, "online reader must precede body notes and download list");
await expect(page.getByText("第 1 页 · 已显示")).toBeVisible({ timeout: 15000 });
await expect.poll(() => page.locator('.pdf-page[data-page="1"] canvas').evaluate((c) => c.width > 0 && c.height > 0)).toBeTruthy();
await mkdir("test-results/new-features-ui", { recursive: true });
await page.screenshot({ path: "test-results/new-features-ui/pdf-desktop.png", fullPage: false });
await page.locator(".pdf-continuous").hover();
await page.mouse.wheel(0, 1800);
await expect(page.getByText("第 2 页 · 已显示")).toBeVisible({ timeout: 15000 });
await expect(page.getByLabel("页码")).toHaveValue("2");
await page.screenshot({ path: "test-results/new-features-ui/pdf-wheel-page2.png", fullPage: false });
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(`${base}/problems/p1`);
await expect(page.getByText("第 1 页 · 已显示")).toBeVisible({ timeout: 15000 });
await page.getByLabel(/PDF 阅读器/).scrollIntoViewIfNeeded();
await page.screenshot({ path: "test-results/new-features-ui/pdf-mobile.png", fullPage: false });
await page.goto(`${base}/articles/a1`);
await expect(page.locator(".markdown")).toBeVisible();
await page.getByRole("button", { name: "回复" }).click();
await page.screenshot({ path: "test-results/new-features-ui/comments-mobile.png", fullPage: true });
assert.deepEqual(errors, []);
await browser.close();
console.log("New feature UI checks passed.");
